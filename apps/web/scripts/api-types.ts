import { buildOpenApiDocument } from '@easyfi/contracts';
import openapiTS, { astToString } from 'openapi-typescript';

export const API_TYPES_FILE = new URL('../src/lib/api/schema.d.ts', import.meta.url);

/** TypeScript `paths` / `components` types for the /api/v1 OpenAPI document. */
export async function generateApiTypes(): Promise<string> {
  const doc = buildOpenApiDocument();
  // request fields with a zod default are optional for callers
  const ast = await openapiTS(doc as never, { defaultNonNullable: false });
  return `// GENERATED by \`pnpm --filter @easyfi/web gen:api\` from @easyfi/contracts. Do not edit.\n${astToString(ast)}`;
}
